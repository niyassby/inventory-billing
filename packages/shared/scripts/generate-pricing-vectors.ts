/**
 * Regenerates test-vectors/pricing.json from the TypeScript pricing engine.
 * Run only when the pricing rules change on purpose: `npx tsx packages/shared/scripts/generate-pricing-vectors.ts`.
 * The Rust engine (src-tauri/src/domain/pricing.rs) must then pass the new vectors too.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { DocumentInput } from "../src/tax";
import { gstComponents, priceDocument } from "../src/tax";
import { money } from "../src/money";
import { qty } from "../src/qty";

const gst18 = gstComponents(180000, false);
const gst5 = gstComponents(50000, false);
const igst18 = gstComponents(180000, true);

type Case = { name: string; input: DocumentInput };

const line = (price: number, milli: number, extra: object = {}) => ({
  unitPrice: money(price),
  qty: qty(milli),
  taxes: gst18,
  ...extra,
});

const cases: Case[] = [
  { name: "exclusive CGST+SGST", input: { pricesIncludeTax: false, lines: [line(10000, 2000)] } },
  {
    name: "line percent discount before tax",
    input: {
      pricesIncludeTax: false,
      lines: [line(10000, 2000, { discount: { kind: "percent", rate: 100000 } })],
    },
  },
  {
    name: "line amount discount",
    input: {
      pricesIncludeTax: false,
      lines: [line(9999, 3000, { discount: { kind: "amount", amount: money(1234) } })],
    },
  },
  {
    name: "bill discount spread pro-rata",
    input: {
      pricesIncludeTax: false,
      lines: [line(10000, 1000), line(5000, 1000)],
      billDiscount: { kind: "amount", amount: money(1000) },
    },
  },
  {
    name: "percent bill discount",
    input: {
      pricesIncludeTax: false,
      lines: [line(10000, 1000)],
      billDiscount: { kind: "percent", rate: 50000 },
    },
  },
  {
    name: "mixed rates and untaxed",
    input: {
      pricesIncludeTax: false,
      lines: [
        line(10000, 1000),
        line(10000, 1000, { taxes: gst5 }),
        line(500, 1000, { taxes: [] }),
      ],
    },
  },
  {
    name: "inclusive IGST",
    input: { pricesIncludeTax: true, lines: [line(11800, 1000, { taxes: igst18 })] },
  },
  {
    name: "inclusive split remainder",
    input: { pricesIncludeTax: true, lines: [line(10000, 1000)] },
  },
  {
    name: "inclusive with discounts and fractional qty",
    input: {
      pricesIncludeTax: true,
      lines: [
        line(4550, 1255, { discount: { kind: "percent", rate: 25000 } }),
        line(19900, 2000, { taxes: gst5 }),
      ],
      billDiscount: { kind: "amount", amount: money(733) },
    },
  },
  {
    name: "round-off up",
    input: {
      pricesIncludeTax: false,
      lines: [line(1050, 1000, { taxes: [] })],
      roundTotalTo: money(100),
    },
  },
  {
    name: "round-off down",
    input: {
      pricesIncludeTax: false,
      lines: [line(1049, 1000, { taxes: [] })],
      roundTotalTo: money(100),
    },
  },
  {
    name: "half-even rounding",
    input: {
      pricesIncludeTax: false,
      lines: [line(1001, 500, { taxes: [] })],
      rounding: "half_even",
    },
  },
  { name: "empty document", input: { pricesIncludeTax: false, lines: [] } },
  {
    name: "vat single component",
    input: {
      pricesIncludeTax: false,
      lines: [line(2599, 7000, { taxes: [{ code: "VAT", rate: 50000 }] })],
    },
  },
];

const errors: Case[] = [
  { name: "zero quantity", input: { pricesIncludeTax: false, lines: [line(100, 0)] } },
  { name: "negative price", input: { pricesIncludeTax: false, lines: [line(-1, 1000)] } },
  {
    name: "discount above amount",
    input: {
      pricesIncludeTax: false,
      lines: [line(100, 1000, { discount: { kind: "amount", amount: money(101) } })],
    },
  },
  {
    name: "bill discount rate above 100%",
    input: {
      pricesIncludeTax: false,
      lines: [line(100, 1000)],
      billDiscount: { kind: "percent", rate: 2_000_000 },
    },
  },
];

for (const e of errors) {
  try {
    priceDocument(e.input);
    throw new Error(`expected "${e.name}" to fail`);
  } catch (error) {
    if (error instanceof Error && error.message.startsWith("expected")) throw error;
  }
}

const out = {
  $comment:
    "Generated by packages/shared/scripts/generate-pricing-vectors.ts from the TypeScript engine. The Rust engine must produce identical results.",
  cases: cases.map((c) => ({ ...c, expected: priceDocument(c.input) })),
  errors: errors.map((e) => ({ name: e.name, input: e.input })),
};
const target = fileURLToPath(new URL("../test-vectors/pricing.json", import.meta.url));
writeFileSync(target, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${out.cases.length} cases and ${out.errors.length} error cases to ${target}`);
