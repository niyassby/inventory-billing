/**
 * Turns the Rust API contract (src/generated/api-schema.json, written by
 * `UPDATE_CONTRACT=1 cargo test contract`) into TypeScript types: src/generated/api.ts.
 *
 *   npm run gen:api            regenerate
 *   npm run gen:api -- --check fail if api.ts is stale (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import type { JSONSchema4 } from "json-schema";

const schemaPath = fileURLToPath(new URL("../src/generated/api-schema.json", import.meta.url));
const outputPath = fileURLToPath(new URL("../src/generated/api.ts", import.meta.url));

const schema = JSON.parse(readFileSync(schemaPath, "utf8")) as JSONSchema4;
const items = schema.properties?.publicCommands?.items;
const publicCommands = items && !Array.isArray(items) ? items.enum : undefined;
if (!Array.isArray(publicCommands)) throw new Error("api-schema.json: publicCommands missing");
const localItems = schema.properties?.localCommands?.items;
const localCommands = localItems && !Array.isArray(localItems) ? localItems.enum : undefined;
if (!Array.isArray(localCommands)) throw new Error("api-schema.json: localCommands missing");

const types = await compile(schema, "ApiContract", {
  bannerComment: "",
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { printWidth: 100, semi: true, singleQuote: false, trailingComma: "all" },
});

const output = `/* eslint-disable */
// Generated by packages/shared/scripts/generate-api-types.ts from api-schema.json. Do not edit.

${types}
export type CommandName = keyof ApiContract["commands"];
export type CommandInput<K extends CommandName> = ApiContract["commands"][K]["input"];
export type CommandOutput<K extends CommandName> = ApiContract["commands"][K]["output"];
export type ApiErrorPayload = ApiContract["error"];
export type Approval = ApiContract["approval"];

/** Commands that work without a session (setup and sign-in). */
export const PUBLIC_COMMANDS = ${JSON.stringify(publicCommands)} as const satisfies readonly CommandName[];

/** Commands about this PC itself; never forwarded to the hub. */
export const LOCAL_COMMANDS = ${JSON.stringify(localCommands)} as const satisfies readonly CommandName[];
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8").replace(/\r\n/g, "\n");
  if (current !== output) {
    console.error("src/generated/api.ts is stale: run `npm run gen:api` and commit it.");
    process.exit(1);
  }
  console.log("api.ts is up to date");
} else {
  writeFileSync(outputPath, output);
  console.log(`wrote ${outputPath}`);
}
